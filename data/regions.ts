export function getRegionBySlug(rawSlug: string): RegionData | undefined {
  if (!rawSlug || typeof rawSlug !== 'string') return undefined

  // Normalize slug: strip trailing/leading slashes, lowercase, and handle optional suffixes
  const normalized = rawSlug
    .toLowerCase()
    .replace(/-reverse-sales-tax-calculator$/, '')
    .replace(/^reverse-sales-tax-calculator-/, '')
    .replace(/-sales-tax-calculator$/, '')
    .replace(/-sales-tax$/, '')
    .trim()

  return REGIONS.find(
    (r) =>
      r.slug === normalized ||
      r.slug === rawSlug.toLowerCase() ||
      r.name.toLowerCase() === normalized.replace(/-/g, ' ')
  )
}
