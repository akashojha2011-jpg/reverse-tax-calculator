export function getStateTaxData(slugOrAbbr: string): StateTaxData | undefined {
  if (!slugOrAbbr) return undefined
  const query = slugOrAbbr.toLowerCase().trim()
  return (
    US_TAX_RATES[query] ||
    Object.values(US_TAX_RATES).find(
      (s) => s.abbr.toLowerCase() === query || s.name.toLowerCase() === query
    )
  )
}

